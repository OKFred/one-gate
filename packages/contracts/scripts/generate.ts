import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validate, type Schema } from '@cfworker/json-schema';
import { compileBackendSchemas } from '../src/backend.js';
import { resolveResourceMeta } from '../src/defaults.js';
import type { CrudResourceContract } from '../src/types.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const PKG_ROOT = path.resolve(__dirname, '..');
const RESOURCES_DIR = path.join(PKG_ROOT, 'src', 'resources');
const GENERATED_DIR = path.join(PKG_ROOT, 'src', 'generated');
const SCHEMA_PATH = path.join(PKG_ROOT, 'schema', 'crud-resource.schema.json');

function collectJsonFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  const results: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectJsonFiles(full));
    } else if (entry.isFile() && entry.name.endsWith('.json')) {
      results.push(full);
    }
  }
  return results.sort();
}

function toCamelCase(input: string): string {
  return input
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part, idx) =>
      idx === 0
        ? part.charAt(0).toLowerCase() + part.slice(1)
        : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join('');
}

function ensureDir(dirPath: string): void {
  fs.mkdirSync(dirPath, { recursive: true });
}

function cleanStaleGenerated(dirPath: string): void {
  if (fs.existsSync(dirPath)) {
    fs.rmSync(dirPath, { recursive: true, force: true });
  }
  ensureDir(dirPath);
}

function toPosix(p: string): string {
  return p.split(path.sep).join('/');
}

async function main(): Promise<void> {
  const metaSchema = JSON.parse(fs.readFileSync(SCHEMA_PATH, 'utf8')) as Schema;
  const jsonFiles = collectJsonFiles(RESOURCES_DIR);

  cleanStaleGenerated(GENERATED_DIR);
  const generatedResourcesDir = path.join(GENERATED_DIR, 'resources');
  ensureDir(generatedResourcesDir);

  const manifestEntries: Array<{
    resource: string;
    app: string;
    route: string;
    mountRoute: boolean;
    importPath: string;
    exportName: string;
  }> = [];

  const resourceReexports: Array<{
    importPath: string;
    contractExport: string;
    schemasExport: string;
  }> = [];

  const seenResources = new Set<string>();
  const seenRoutes = new Set<string>();
  const usedExportNames = new Set<string>();

  for (const filePath of jsonFiles) {
    const relFromResources = path.relative(RESOURCES_DIR, filePath);
    const relNoExt = relFromResources.replace(/\.json$/, '');
    const contract = JSON.parse(fs.readFileSync(filePath, 'utf8')) as CrudResourceContract;

    const validation = validate(contract, metaSchema, '2020-12');
    if (!validation.valid) {
      const msg = validation.errors
        .map((e) => `${e.instanceLocation || '/'}: ${e.error}`)
        .join('\n  ');
      throw new Error(`Contract schema validation failed for ${toPosix(relFromResources)}:\n  ${msg}`);
    }

    if (seenResources.has(contract.resource)) {
      throw new Error(`Duplicate resource identifier "${contract.resource}" in ${toPosix(relFromResources)}`);
    }
    seenResources.add(contract.resource);

    const meta = resolveResourceMeta(contract);
    if (meta.mountRoute) {
      const routeKey = `${meta.app}:${meta.route}`;
      if (seenRoutes.has(routeKey)) {
        throw new Error(`Duplicate route "${routeKey}" in ${toPosix(relFromResources)}`);
      }
      seenRoutes.add(routeKey);
    }

    const compiled = compileBackendSchemas(contract);
    let baseCamel = toCamelCase(relNoExt);
    while (usedExportNames.has(baseCamel)) {
      baseCamel = `${baseCamel}Resource`;
    }
    usedExportNames.add(baseCamel);

    const contractExport = `${baseCamel}Contract`;
    const schemasExport = `${baseCamel}BackendSchemas`;

    const outTsPath = path.join(generatedResourcesDir, `${relNoExt}.ts`);
    ensureDir(path.dirname(outTsPath));

    const relToTypes = toPosix(
      path.relative(path.dirname(outTsPath), path.join(PKG_ROOT, 'src', 'types.js')),
    );

    const fileContent = [
      '// This file is auto-generated by @hodor/contracts (scripts/generate.ts).',
      '// Do not edit this file manually.',
      `import type { CrudResourceContract } from '${relToTypes}';`,
      '',
      `export const ${contractExport} = ${JSON.stringify(contract, null, 2)} as const satisfies CrudResourceContract;`,
      '',
      `export const ${schemasExport} = ${JSON.stringify(compiled, null, 2)} as const;`,
      '',
    ].join('\n');

    fs.writeFileSync(outTsPath, fileContent, 'utf8');

    const posixRelNoExt = toPosix(relNoExt);
    resourceReexports.push({
      importPath: `./${posixRelNoExt}.js`,
      contractExport,
      schemasExport,
    });

    manifestEntries.push({
      resource: contract.resource,
      app: meta.app,
      route: meta.route,
      mountRoute: meta.mountRoute,
      importPath: `./resources/${posixRelNoExt}.js`,
      exportName: contractExport,
    });
  }

  const resourcesIndexLines = [
    '// This file is auto-generated by @hodor/contracts (scripts/generate.ts).',
    '// Do not edit this file manually.',
    ...resourceReexports.map(
      (r) => `export { ${r.contractExport}, ${r.schemasExport} } from '${r.importPath}';`,
    ),
    '',
  ];
  fs.writeFileSync(
    path.join(generatedResourcesDir, 'index.ts'),
    resourcesIndexLines.join('\n'),
    'utf8',
  );

  const manifestLines = [
    '// This file is auto-generated by @hodor/contracts (scripts/generate.ts).',
    '// Do not edit this file manually.',
    "import type { AppScope, CrudResourceContract } from '../types.js';",
    '',
    'export interface ContractRouteEntry {',
    '  readonly resource: string;',
    '  readonly app: AppScope;',
    '  readonly route: string;',
    '  readonly mountRoute: boolean;',
    '  readonly load: () => Promise<{ readonly default: CrudResourceContract }>;',
    '}',
    '',
    'export const contractManifest: readonly ContractRouteEntry[] = [',
    ...manifestEntries.map(
      (m) =>
        `  {\n` +
        `    resource: ${JSON.stringify(m.resource)},\n` +
        `    app: ${JSON.stringify(m.app)},\n` +
        `    route: ${JSON.stringify(m.route)},\n` +
        `    mountRoute: ${String(m.mountRoute)},\n` +
        `    load: () => import('${m.importPath}').then((mod) => ({ default: mod.${m.exportName} })),\n` +
        `  },`,
    ),
    '];',
    '',
  ];
  fs.writeFileSync(path.join(GENERATED_DIR, 'manifest.ts'), manifestLines.join('\n'), 'utf8');

  console.log(`✅ Generated ${manifestEntries.length} contract module(s) into src/generated/`);
}

await main();
